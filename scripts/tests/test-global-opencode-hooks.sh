#!/usr/bin/env bash
# Behavioural mirror for install.sh --hooks --global opencode.
#
# The OpenCode bridge is one generated .js file under the auto-discovered
# global plugins dir (~/.config/opencode/plugins/): no settings merge, no
# directory scan. The dangerous surfaces are overwriting a user's own
# plugin file and deleting anything the kit cannot prove it owns, so those
# cases assert byte-identical files and a surviving decoy user plugin.
# Hermetic HOME + XDG_CONFIG_HOME per case.
set -uo pipefail

kit="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

command -v node >/dev/null 2>&1 || {
	echo "global opencode hooks mirror: node is required to test the bridge; nothing installed" >&2
	exit 1
}

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

passed=0
failed=0
ok() {
	printf 'ok - %s\n' "$1"
	passed=$((passed + 1))
}
no() {
	printf 'not ok - %s\n' "$1"
	failed=$((failed + 1))
}

# run_install <home> <xdg> <args...> -- installer under a hermetic env.
run_install() {
	local h="$1" x="$2"
	shift 2
	HOME="$h" XDG_CONFIG_HOME="$x" "${kit}/install.sh" "$@" </dev/null
}
plugindir_of() { printf '%s/opencode/plugins' "$1"; }
bridge_of() { printf '%s/eshu-bridge.js' "$(plugindir_of "$1")"; }

# 1. Fresh install: bridge lands with this checkout baked in and the marker.
h1="${work}/h1"
x1="${work}/x1"
if run_install "$h1" "$x1" --hooks --global opencode >/dev/null 2>&1; then
	ok "global opencode install succeeds"
else
	no "global opencode install succeeds"
fi
rg -qF -- '// Generated by eshu-agent-kit install.sh --hooks --global opencode; do not edit.' "$(bridge_of "$x1")" &&
	rg -qF -- "${kit}\"" "$(bridge_of "$x1")" &&
	ok "bridge carries the marker and the kit path" || no "bridge carries the marker and the kit path"
[ ! -e "$x1/opencode/opencode.jsonc" ] &&
	ok "install merges no settings file" || no "install merges no settings file"

# 2. The installed bridge is valid JavaScript and its unit tests pass.
if node --check "$(bridge_of "$x1")" 2>/dev/null; then
	ok "installed bridge parses as JavaScript"
else
	no "installed bridge parses as JavaScript"
fi
# The bridge template carries an unsubstituted %%KIT_DIR%% until install;
# point it at this checkout so the tests drive the real siblings.
# node --test exits non-zero on any failure; the exit code (not TAP text,
# whose summary format differs between node versions) is the assertion.
node_out="$(ESHU_KIT_DIR="${kit}" node --test "${kit}/plugins/opencode/tests/test-bridge.js" 2>&1)"
node_status=$?
if [ "${node_status}" -eq 0 ]; then
	ok "bridge unit and sibling tests pass"
else
	printf '%s\n' "${node_out}" >&2
	no "bridge unit and sibling tests pass (node exit ${node_status})"
fi

# 3. Reinstall is byte-identical and says unchanged.
before="$(cat "$(bridge_of "$x1")")"
out="$(run_install "$h1" "$x1" --hooks --global opencode 2>&1)" &&
	[ "$(cat "$(bridge_of "$x1")")" = "${before}" ] && rg -q 'unchanged' <<<"${out}" &&
	ok "reinstall is a byte-identical no-op" || no "reinstall is a byte-identical no-op"

# 4. A foreign file with the same name is refused, byte-identical.
printf '// mine, hands off\n' >"$(bridge_of "$x1")"
if run_install "$h1" "$x1" --hooks --global opencode >/dev/null 2>&1; then
	no "foreign bridge file is refused"
else
	[ "$(cat "$(bridge_of "$x1")")" = '// mine, hands off' ] &&
		ok "foreign bridge file is refused" || no "foreign bridge file is refused"
fi

# 5. Uninstall removes the kit bridge and prints the removal.
h5="${work}/h5"
x5="${work}/x5"
run_install "$h5" "$x5" --hooks --global opencode >/dev/null 2>&1
printf '// a user plugin the kit must never touch\n' >"$(plugindir_of "$x5")/mine.js"
out="$(run_install "$h5" "$x5" --uninstall --hooks --global opencode 2>&1)"
[ ! -e "$(bridge_of "$x5")" ] && rg -q 'removed .*eshu-bridge.js' <<<"${out}" &&
	ok "uninstall removes the kit bridge" || no "uninstall removes the kit bridge"
[ "$(cat "$(plugindir_of "$x5")/mine.js")" = '// a user plugin the kit must never touch' ] &&
	ok "uninstall leaves user plugins alone" || no "uninstall leaves user plugins alone"

# 6. Uninstall keeps a modified bridge and says how to finish.
h6="${work}/h6"
x6="${work}/x6"
run_install "$h6" "$x6" --hooks --global opencode >/dev/null 2>&1
printf '// edited by hand\n' >>"$(bridge_of "$x6")"
out="$(run_install "$h6" "$x6" --uninstall --hooks --global opencode 2>&1)"
[ -e "$(bridge_of "$x6")" ] && rg -q 'keeping .*remove by hand' <<<"${out}" &&
	ok "uninstall keeps a modified bridge" || no "uninstall keeps a modified bridge"

# 7. Uninstall with nothing installed reports the keep, not a removal.
h7="${work}/h7"
x7="${work}/x7"
mkdir -p "$(plugindir_of "$x7")"
out="$(run_install "$h7" "$x7" --uninstall --hooks --global opencode 2>&1)"
rg -q 'keeping .*no kit bridge installed' <<<"${out}" &&
	ok "empty uninstall reports the keep" || no "empty uninstall reports the keep"

# 8. Bare global uninstall keeps the bridge and names the explicit undo,
# the same way the Muse tree is kept: hooks are never removed as a side
# effect of a broad uninstall.
h8="${work}/h8"
x8="${work}/x8"
run_install "$h8" "$x8" --hooks --global opencode >/dev/null 2>&1
out="$(run_install "$h8" "$x8" --uninstall --global opencode 2>&1)"
[ -f "$(bridge_of "$x8")" ] && rg -q 'keeping .*--uninstall --hooks --global opencode' <<<"${out}" &&
	ok "bare global uninstall keeps the bridge with its undo" || no "bare global uninstall keeps the bridge with its undo"

# 9. The sed substitution survives hostile checkout paths: the escaping
# helper round-trips &, |, and backslash through the same expression the
# writer uses, so KIT_DIR can contain any of them.
# shellcheck source=scripts/lib/install-hooks-global-opencode.sh
. "${kit}/scripts/lib/install-hooks-global-opencode.sh"
[ "$(opencode_escape_sed 'a&b|c\d')" = 'a\&b\|c\\d' ] &&
	[ "$(printf '%%%%KIT_DIR%%%%' | sed -e "s|%%KIT_DIR%%|$(opencode_escape_sed 'a&b|c\d')|g")" = 'a&b|c\d' ] &&
	ok "kit path escaping round-trips" || no "kit path escaping round-trips"

printf '\nglobal opencode hooks mirror: %s passed, %s failed\n' "${passed}" "${failed}"
[[ "${failed}" -eq 0 ]]
