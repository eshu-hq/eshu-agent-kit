#!/usr/bin/env bash
# Behavioural mirror for install-time pruning of stale kit artifacts.
#
# Reinstalls must remove what the kit provably owns and nothing else, print
# each removal, and respect --no-prune. Ownership proof is the safety case:
# symlinks resolving into this kit (or dangling links whose raw target names
# an eshu-agent-kit path), and regular files carrying the Generated-by
# marker. User files, real directories, out-of-kit links, and the superseded
# ~/.agents/agents (prior model choices) always survive.
set -euo pipefail

kit="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
unset XDG_CONFIG_HOME

passed=0
failed=0
ok() {
	printf 'ok - %s\n' "$1"
	passed=$((passed + 1))
}
no() {
	printf 'not ok - %s\n' "$1"
	failed=$((failed + 1))
}

# 1. Repo agents: stale kit symlink + stale generated copy are pruned and
# printed; user file, out-of-kit link, and current agents survive.
repo="${work}/repo"
"${kit}/install.sh" --agents --repo "${repo}" >/dev/null 2>&1
ln -s "${kit}/.claude/agents/scan-eshu.md" "${repo}/.claude/agents/old-role.md"
printf -- '---\nname: old-role\n---\n\n<!-- Generated by agents/agent-roles.py from agents/roles.json; do not edit. -->\n' \
	>"${repo}/.agents/agents/old-role.md"
printf '# mine\n' >"${repo}/.agents/agents/mine.md"
printf 'x\n' >"${work}/outside.md"
ln -s "${work}/outside.md" "${repo}/.claude/agents/ext-link.md"
out="$("${kit}/install.sh" --agents --repo "${repo}" 2>/dev/null)"
[ ! -e "${repo}/.claude/agents/old-role.md" ] && [ ! -L "${repo}/.claude/agents/old-role.md" ] &&
	ok "stale kit symlink pruned on reinstall" || no "stale kit symlink pruned on reinstall"
[ ! -e "${repo}/.agents/agents/old-role.md" ] &&
	ok "stale generated copy pruned on reinstall" || no "stale generated copy pruned on reinstall"
rg -q "pruned stale kit artifact: ${repo}/.claude/agents/old-role.md" <<<"${out}" &&
	rg -q "pruned stale kit artifact: ${repo}/.agents/agents/old-role.md" <<<"${out}" &&
	ok "each pruning is printed" || no "each pruning is printed"
[ "$(cat "${repo}/.agents/agents/mine.md")" = "# mine" ] &&
	ok "unmarked user file survives" || no "unmarked user file survives"
[ -L "${repo}/.claude/agents/ext-link.md" ] &&
	ok "out-of-kit symlink survives" || no "out-of-kit symlink survives"
cmp -s "${repo}/.agents/agents/scan-eshu.md" "${kit}/agents/scan-eshu.md" &&
	ok "current agents untouched by prune" || no "current agents untouched by prune"

# 2. Dangling links: an old-kit-path target is stale kit property, an
# unrelated dangling target is not ours to remove.
ln -s "/gone/eshu-agent-kit/agents/old-role.md" "${repo}/.agents/agents/dangling-kit.md"
ln -s "/gone/.worktrees/eshu-agent-kit-old-branch/agents/old-role.md" "${repo}/.agents/agents/dangling-worktree.md"
ln -s "/gone/other/old.md" "${repo}/.agents/agents/dangling-ext.md"
"${kit}/install.sh" --agents --repo "${repo}" >/dev/null 2>&1
[ ! -L "${repo}/.agents/agents/dangling-kit.md" ] &&
	ok "dangling old-kit-path link pruned" || no "dangling old-kit-path link pruned"
[ ! -L "${repo}/.agents/agents/dangling-worktree.md" ] &&
	ok "dangling deleted-worktree link pruned" || no "dangling deleted-worktree link pruned"
[ -L "${repo}/.agents/agents/dangling-ext.md" ] &&
	ok "unrelated dangling link survives" || no "unrelated dangling link survives"

# 3. --no-prune keeps stale kit artifacts in place.
ln -s "${kit}/.claude/agents/scan-eshu.md" "${repo}/.claude/agents/old-role.md"
"${kit}/install.sh" --agents --repo "${repo}" --no-prune >/dev/null 2>&1
[ -L "${repo}/.claude/agents/old-role.md" ] &&
	ok "--no-prune leaves stale kit artifacts" || no "--no-prune leaves stale kit artifacts"
rm "${repo}/.claude/agents/old-role.md"

# 3b. rules/README.md is in the source glob but never installed; a kit link
# under that name is stale, not kept.
"${kit}/install.sh" --rules --repo "${repo}" >/dev/null 2>&1
ln -s "${kit}/rules/README.md" "${repo}/.claude/rules/README.md"
"${kit}/install.sh" --rules --repo "${repo}" >/dev/null 2>&1
[ ! -L "${repo}/.claude/rules/README.md" ] &&
	ok "never-installed rules README link pruned" || no "never-installed rules README link pruned"

# 4. A real directory (alias wrappers are real dirs with copied content)
# is never pruned, even under a managed skills dir.
mkdir -p "${repo}/.agents/skills/my-alias"
printf 'x\n' >"${repo}/.agents/skills/my-alias/SKILL.md"
"${kit}/install.sh" --repo "${repo}" >/dev/null 2>&1
[ -f "${repo}/.agents/skills/my-alias/SKILL.md" ] &&
	ok "real directory under managed skills survives" || no "real directory under managed skills survives"

# 5. Global muse: stale generated agent pruned, unmarked file survives,
# stale skill link pruned, superseded ~/.agents/agents never touched.
home1="${work}/home1"
HOME="${home1}" "${kit}/install.sh" --global muse </dev/null >/dev/null 2>&1
printf -- '---\nname: old-role\n---\n\n<!-- Generated by agents/agent-roles.py from agents/roles.json; do not edit. -->\n' \
	>"${home1}/.config/muse/agents/old-role.md"
printf '# keep\n' >"${home1}/.config/muse/agents/keep.md"
skill_src="$(ls "${kit}/skills/eshu" | head -n 1)"
ln -s "${kit}/skills/eshu/${skill_src}" "${home1}/.agents/skills/old-skill"
mkdir -p "${home1}/.agents/agents"
printf '# prior choice\n' >"${home1}/.agents/agents/scan-eshu.md"
HOME="${home1}" "${kit}/install.sh" --global muse </dev/null >/dev/null 2>&1
[ ! -e "${home1}/.config/muse/agents/old-role.md" ] &&
	ok "stale global agent pruned" || no "stale global agent pruned"
[ "$(cat "${home1}/.config/muse/agents/keep.md")" = "# keep" ] &&
	ok "unmarked global agent survives" || no "unmarked global agent survives"
[ ! -L "${home1}/.agents/skills/old-skill" ] &&
	ok "stale global skill link pruned" || no "stale global skill link pruned"
[ "$(cat "${home1}/.agents/agents/scan-eshu.md")" = "# prior choice" ] &&
	ok "superseded ~/.agents/agents untouched" || no "superseded ~/.agents/agents untouched"

printf '\ninstall-prune mirror: %s passed, %s failed\n' "${passed}" "${failed}"
[[ "${failed}" -eq 0 ]]
