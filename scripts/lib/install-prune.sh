# Stale-artifact pruning for kit installs. Sourced by install.sh; extracted
# to keep the entrypoint under the 500-line cap, like install-aliases.sh.
# shellcheck shell=bash
#
# Reinstalls only ever added links and files, so a renamed or removed skill,
# role, hook, or rule lingered forever in consumer trees. prune_dir removes,
# inside directories the current run manages, only what the kit provably
# owns, and prints every removal:
#   - symlinks whose canonical target lies inside this kit, plus dangling
#     symlinks whose raw target names an eshu-agent-kit* path segment (a kit
#     checkout or worktree that moved or was deleted since the link was made);
#   - regular files carrying the Generated-by marker agents/agent-roles.py
#     stamps on every generated agent file.
# Never pruned: unmarked regular files, real directories (alias wrappers are
# real dirs with copied content), symlinks resolving outside the kit, and
# anything in a directory the current run does not manage -- notably the
# superseded ~/.agents/agents, which holds prior per-agent model choices.

# --no-prune is accepted anywhere after the mode token and stripped here so
# mode parsing in install.sh never sees it.
PRUNE=1
_prune_kept=()
for _prune_arg in "$@"; do
	if [ "$_prune_arg" = --no-prune ]; then
		PRUNE=0
	else
		_prune_kept+=("$_prune_arg")
	fi
done
if [ "${#_prune_kept[@]}" -gt 0 ] && [ "${#_prune_kept[@]}" -ne "$#" ]; then
	set -- "${_prune_kept[@]}"
fi
unset _prune_arg _prune_kept

PRUNE_MARKER='Generated by agents/agent-roles.py from agents/roles.json; do not edit.'

# prune_resolve <link> -- canonical absolute target of a symlink (the final
# component need not exist), or empty when the target directory is gone.
# Hand-rolled instead of readlink -f, which BSD readlink lacks.
prune_resolve() {
	local raw dir
	raw="$(readlink "$1")" || return 0
	case "$raw" in
	/*) dir="$(dirname "$raw")" ;;
	*) dir="$(dirname "$1")/$(dirname "$raw")" ;;
	esac
	[ -d "$dir" ] || return 0
	printf '%s/%s\n' "$(cd "$dir" 2>/dev/null && pwd -P)" "$(basename "$raw")"
}

# prune_dir <dest> <source-glob...> -- drop stale kit-owned entries directly
# under dest whose basename no source entry carries any more.
prune_dir() {
	[ "$PRUNE" = 1 ] || return 0
	local dest="$1"
	shift
	[ -d "$dest" ] || return 0
	local keep=" " pat f e base resolved content kit_real
	for pat in "$@"; do
		for f in $pat; do
			[ -e "$f" ] || continue
			keep="$keep$(basename "$f") "
		done
	done
	kit_real="$(cd "$KIT_DIR" 2>/dev/null && pwd -P)"
	for e in "$dest"/*; do
		[ -e "$e" ] || [ -L "$e" ] || continue
		base="$(basename "$e")"
		case "$keep" in
		*" $base "*) continue ;;
		esac
		if [ -L "$e" ]; then
			resolved="$(prune_resolve "$e")"
			case "$resolved" in
			"$KIT_DIR"/* | "$kit_real"/*) ;;
			?*) continue ;;
			*)
				case "$(readlink "$e")" in
				*/eshu-agent-kit*/* | eshu-agent-kit*/*) ;;
				*) continue ;;
				esac
				;;
			esac
		elif [ -f "$e" ]; then
			content="$(head -n 12 "$e" 2>/dev/null)" || continue
			case "$content" in
			*"$PRUNE_MARKER"*) ;;
			*) continue ;;
			esac
		else
			continue
		fi
		rm -f "$e"
		printf 'pruned stale kit artifact: %s\n' "$e"
	done
}
