# Global OpenCode hooks bridge (--hooks --global opencode). Sourced by
# install.sh; extracted to keep the entrypoint under the 500-line cap, like
# install-hooks-global.sh. Registration needs no settings merge: OpenCode
# auto-discovers plain .js files under ~/.config/opencode/plugins/, so the
# installer copies one kit-owned bridge file there.
#
# Ownership never iterates the shared plugins directory: that tree holds
# user plugins the kit must not inventory, let alone delete. The bridge
# file carries a Generated-by marker, and uninstall proves ownership by
# regenerating the expected content to a temp file and byte-comparing
# (the managed-hooks.json precedent), never by scanning the directory.
# shellcheck shell=bash

opencode_plugin_dir() { printf '%s\n' "${XDG_CONFIG_HOME:-$HOME/.config}/opencode/plugins"; }

OPENCODE_BRIDGE_NAME='eshu-bridge.js'
OPENCODE_BRIDGE_MARKER='// Generated by eshu-agent-kit install.sh --hooks --global opencode; do not edit.'

# opencode_escape_sed <string> -- escape a replacement string for sed's
# s|a|b|: backslashes first, then the delimiter and &. A checkout path
# containing any of those would otherwise corrupt the installed bridge.
opencode_escape_sed() {
	printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/[|&]/\\&/g'
}

# write_opencode_plugin <dest> -- render the bridge from the kit template
# with this checkout's absolute path baked in (the global plugin must
# resolve its siblings without trusting the repo it runs in) and print
# the destination. Tmp file plus rename, like every other kit writer.
write_opencode_plugin() {
	local dest="$1" tmp
	tmp="$(mktemp "$(dirname "$dest")/.eshu-bridge-XXXXXX")" || return 1
	{
		printf '%s\n' "${OPENCODE_BRIDGE_MARKER}"
		sed -e "s|%%KIT_DIR%%|$(opencode_escape_sed "${KIT_DIR}")|g" "$KIT_DIR/plugins/opencode/eshu-bridge.js"
	} >"$tmp" || {
		rm -f "$tmp"
		return 1
	}
	mv "$tmp" "$dest" || {
		rm -f "$tmp"
		return 1
	}
	printf '%s\n' "$dest"
}

install_hooks_global_opencode() {
	local dir dest expected
	dir="$(opencode_plugin_dir)"
	dest="$dir/${OPENCODE_BRIDGE_NAME}"
	echo "warning: global OpenCode hooks run in-process with every workspace, including untrusted ones; the bridge shells out only to this kit checkout ($KIT_DIR)" >&2
	mkdir -p "$dir" || {
		echo "error: cannot create $dir; nothing installed" >&2
		return 1
	}
	if [ -e "$dest" ] || [ -L "$dest" ]; then
		expected="$(mktemp)" || return 1
		if write_opencode_plugin "$expected" >/dev/null 2>&1 && cmp -s "$dest" "$expected"; then
			rm -f "$expected"
			echo "$dest already installs the kit bridge; unchanged"
			return 0
		fi
		rm -f "$expected"
		echo "refusing: $dest already exists and differs from the kit bridge; move it aside by hand, then rerun" >&2
		return 1
	fi
	write_opencode_plugin "$dest" >/dev/null || {
		echo "error: cannot write $dest; nothing installed" >&2
		return 1
	}
	echo "installed global OpenCode bridge ($dest)"
	echo "undo: ./install.sh --uninstall --hooks --global opencode"
}
